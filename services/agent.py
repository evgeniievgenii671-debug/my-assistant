async def ask_agent(user_id: int, text: str) -> str:
    # Загружаем профиль клиента
    profile = await get_profile(user_id)

    # Формируем блок профиля
    profile_block = ""
    if profile:
        parts = []
        if profile.get("name"):
            parts.append(f"Имя: {profile['name']}")
        if profile.get("phone"):
            parts.append(f"Телефон: {profile['phone']}")
        if profile.get("business"):
            parts.append(f"Бизнес: {profile['business']}")
        if profile.get("city"):
            parts.append(f"Город: {profile['city']}")
        if profile.get("source"):
            parts.append(f"Источник: {profile['source']}")

        if parts:
            profile_block = (
                "\n\n━━━━━━━━━━━━━━━━━━━━\n"
                "ИЗВЕСТНО О КЛИЕНТЕ:\n"
                + "\n".join(parts) +
                "\n━━━━━━━━━━━━━━━━━━━━\n"
                "Не спрашивай повторно эти данные.\n"
            )

    # Собираем сообщения
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT + profile_block}
    ]
    messages += await get_history(user_id)
    messages.append({"role": "user", "content": text})

    answer = None
    for model in (MODEL_MAIN, MODEL_BACKUP):
        try:
            response = await groq.chat.completions.create(
                model=model,
                messages=messages,
                temperature=0.4,
                max_tokens=400,
            )
            answer = response.choices[0].message.content.strip()
            break
        except Exception:
            logger.exception("Groq error on model %s", model)
            continue

    if not answer:
        answer = "Секунду, уточню и вернусь с ответом."

    await add_message(user_id, "user", text)
    await add_message(user_id, "assistant", answer)
    return answer
